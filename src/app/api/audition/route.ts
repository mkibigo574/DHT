import { NextRequest, NextResponse } from 'next/server'
import { queueNotification } from '@/lib/notify'

const SB_URL = process.env.NEXT_PUBLIC_SUPABASE_URL!
const SB_KEY = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!

type AuditionBody = {
  name?: unknown
  email?: unknown
  phone?: unknown
  region?: unknown
  performance_type?: unknown
  genre?: unknown
  video_link?: unknown
  video_path?: unknown
  video_name?: unknown
  video_size?: unknown
  bio?: unknown
}

function str(v: unknown, max = 500): string {
  return typeof v === 'string' ? v.trim().slice(0, max) : ''
}

export async function POST(req: NextRequest) {
  let body: AuditionBody
  try {
    body = await req.json() as AuditionBody
  } catch {
    return NextResponse.json({ ok: false, error: 'Invalid request' }, { status: 400 })
  }

  const name = str(body.name, 200)
  const email = str(body.email, 200)
  const videoLink = str(body.video_link, 1000)
  const videoPath = str(body.video_path, 300)

  if (!name || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    return NextResponse.json({ ok: false, error: 'Please enter your name and a valid email address.' }, { status: 400 })
  }
  if (!videoLink && !videoPath) {
    return NextResponse.json({ ok: false, error: 'Please upload a video or paste a link to one.' }, { status: 400 })
  }
  if (videoLink && !/^https?:\/\/\S+\.\S+/i.test(videoLink)) {
    return NextResponse.json({ ok: false, error: 'The video link should start with https://' }, { status: 400 })
  }
  // Paths are generated by the browser as "<year>/<uuid>-<slug>.<ext>" — reject anything else.
  if (videoPath && !/^\d{4}\/[A-Za-z0-9-]+\.[a-z0-9]{2,5}$/.test(videoPath)) {
    return NextResponse.json({ ok: false, error: 'Invalid video upload. Please try again.' }, { status: 400 })
  }

  const size = Number(body.video_size)
  // Only whitelisted columns are written — the browser can't set status or anything else.
  const record = {
    name,
    email,
    phone: str(body.phone, 50) || null,
    region: str(body.region, 100) || null,
    performance_type: str(body.performance_type, 100) || null,
    genre: str(body.genre, 200) || null,
    bio: str(body.bio, 5000) || null,
    video_link: videoLink || null,
    video_path: videoPath || null,
    video_name: videoPath ? str(body.video_name, 300) || null : null,
    video_size: videoPath && Number.isFinite(size) && size > 0 ? Math.round(size) : null,
  }

  try {
    const res = await fetch(`${SB_URL}/rest/v1/auditions`, {
      method: 'POST',
      headers: {
        apikey: SB_KEY,
        'Content-Type': 'application/json',
        Prefer: 'return=minimal',
      },
      body: JSON.stringify(record),
    })
    if (!res.ok) {
      const err = await res.json().catch(() => ({})) as { message?: string }
      console.error('[audition] insert failed', res.status, err)
      return NextResponse.json({ ok: false, error: err.message ?? 'Submission failed' }, { status: 500 })
    }
  } catch {
    return NextResponse.json({ ok: false, error: 'Server error' }, { status: 500 })
  }

  const siteUrl = process.env.SITE_URL?.replace(/\/$/, '')
  const mb = record.video_size ? ` (${(record.video_size / 1048576).toFixed(1)} MB)` : ''
  queueNotification({
    subject: `🎤 New audition: ${name}${record.performance_type ? ` — ${record.performance_type}` : ''}`,
    heading: 'New audition application',
    replyTo: email,
    fields: [
      ['Name', name],
      ['Email', email],
      ['Phone', record.phone],
      ['Region', record.region],
      ['Performance type', record.performance_type],
      ['Genre', record.genre],
      ['About', record.bio],
      ['Uploaded video', record.video_path ? `${record.video_name ?? 'video'}${mb} — watch it in the admin portal` : null],
      ['Video link', record.video_link],
    ],
    button: record.video_link
      ? { href: record.video_link, label: 'Open video link' }
      : siteUrl
        ? { href: `${siteUrl}/admin`, label: 'Watch in admin portal' }
        : undefined,
  })

  return NextResponse.json({ ok: true })
}
